import { NextRequest, NextResponse } from 'next/server'
import { db } from '@/lib/db'
import { chatComplete, extractJson, type ChatMessage } from '@/lib/ai'

type GenMCQ = { question?: string; options?: string[]; answerIndex?: number; explanation?: string; difficulty?: string }

// AI Quiz Maker: generate fresh MCQs for a chapter.
export async function POST(req: NextRequest) {
  const body = (await req.json()) as { chapterId?: string; count?: number; difficulty?: string }
  const count = Math.max(1, Math.min(10, Number(body.count) || 5))
  if (!body.chapterId) return NextResponse.json({ error: 'chapterId required' }, { status: 400 })

  const ch = await db.chapter.findUnique({ where: { id: body.chapterId } })
  if (!ch) return NextResponse.json({ error: 'Chapter not found' }, { status: 404 })

  const samples = await db.quizQuestion.findMany({ where: { chapterId: ch.id }, take: 2 })
  const hotTopics = (ch.hotTopics as unknown as string[]) ?? []

  const system =
    'You are a CBSE Class 10 board-exam paper setter. You output ONLY valid JSON, no commentary, no markdown fences.'
  const user = `Create exactly ${count} fresh multiple-choice questions for CBSE Class 10, ${ch.book}, Chapter ${ch.number}: "${ch.title}".
${hotTopics.length ? `Focus topics: ${hotTopics.slice(0, 5).join('; ')}.` : ''}
Difficulty mix: mostly ${body.difficulty === 'hard' ? 'hard and medium' : body.difficulty === 'easy' ? 'easy and medium' : 'medium'} level.
Style them like these NCERT-based examples (do NOT copy them):
${JSON.stringify(
  samples.map((s) => ({ question: s.question, options: s.options, answerIndex: s.answerIndex })),
  null,
  0
).slice(0, 1200)}

Return JSON array where each item is:
{"question": "...", "options": ["...","...","...","..."], "answerIndex": 0-3, "explanation": "one or two sentences", "difficulty": "easy"|"medium"|"hard"}
Rules: exactly 4 options; answerIndex must point to the correct option; language must be exam-style English; maths questions must be numerically correct.`

  const messages: ChatMessage[] = [
    { role: 'system', content: system },
    { role: 'user', content: user },
  ]

  try {
    const result = await chatComplete(messages, { temperature: 0.5, maxTokens: 2000 })
    const parsed = extractJson<GenMCQ[]>(result.text)
    const valid = (Array.isArray(parsed) ? parsed : []).filter(
      (q) =>
        q?.question?.trim() &&
        Array.isArray(q.options) &&
        q.options.length === 4 &&
        q.options.every((o) => typeof o === 'string' && o.trim()) &&
        Number.isInteger(q.answerIndex) &&
        (q.answerIndex as number) >= 0 &&
        (q.answerIndex as number) <= 3
    )
    if (!valid.length) return NextResponse.json({ error: 'AI returned no usable questions. Try again.' }, { status: 502 })
    return NextResponse.json({
      questions: valid.slice(0, count).map((q, i) => {
        // Shuffle options so the correct answer is not always in the same position.
        const order = [0, 1, 2, 3].sort(() => Math.random() - 0.5)
        return {
          id: `ai-${Date.now()}-${i}`,
          question: q.question!.trim(),
          options: order.map((oi) => q.options![oi].trim()),
          answerIndex: order.indexOf(q.answerIndex!),
          explanation: (q.explanation ?? '').trim() || 'Generated by AI.',
          difficulty: ['easy', 'medium', 'hard'].includes(q.difficulty ?? '') ? q.difficulty! : 'medium',
          source: 'ai' as const,
        }
      }),
      provider: result.provider,
    })
  } catch (e) {
    return NextResponse.json({ error: `AI quiz generation failed. ${(e as Error).message}` }, { status: 502 })
  }
}
